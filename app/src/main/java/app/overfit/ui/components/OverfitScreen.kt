/** Einheitlicher Screen-Rahmen mit Titelleiste und optionalem Zurück-Button. */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun OverfitScreen(
    title: String,
    onBack: (() -> Unit)? = null,
    content: @Composable (PaddingValues) -> Unit,
) {
    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text(title) },
                navigationIcon = {
                    if (onBack != null) {
                        IconButton(onClick = onBack) {
                            Icon(
                                Icons.AutoMirrored.Filled.ArrowBack,
                                contentDescription = stringResource(R.string.back),
                            )
                        }
                    }
                },
            )
        },
        content = content,
    )
}

/** Zentrierter Hinweistext für leere Listen. */
@Composable
fun EmptyState(text: String, modifier: Modifier = Modifier) {
    Box(modifier.fillMaxSize().padding(32.dp), contentAlignment = Alignment.Center) {
        Text(
            text = text,
            style = MaterialTheme.typography.bodyLarge,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
            textAlign = TextAlign.Center,
        )
    }
}

/** Standardabstände für scrollbare Screen-Inhalte. */
val ScreenContentSpacing = Arrangement.spacedBy(12.dp)
