    private fun QrMatrix.asRows() = (0 until size).map { y ->
        (0 until size).joinToString("") { x -> if (this[x, y]) "1" else "0" }
    }

    @Test
    fun matchesReferenceMatrices() {
        for (ref in refs) {
            assertEquals(ref.mask, chosenQrMask(ref.text), "mask for ${ref.text}")
            assertEquals(ref.rows, encodeQr(ref.text).asRows(), "matrix for ${ref.text}")
        }
    }

    @Test
    fun structureIsValid() {
        val m = encodeQr("https://overfit.app/spot#abc")
        assertEquals(17 + 4 * 3, m.size)
        for ((cx, cy) in listOf(3 to 3, m.size - 4 to 3, 3 to m.size - 4)) assertTrue(m[cx, cy])
        for (i in 8 until m.size - 8) assertEquals(i % 2 == 0, m[i, 6])
        assertTrue(m[8, m.size - 8]) // dark module
    }

    @Test
    fun tooLongTextThrows() {
        assertFailsWith<IllegalArgumentException> { encodeQr("x".repeat(288)) }
    }

    @Test
    fun maxCapacityFitsVersion12() {
        assertEquals(17 + 4 * 12, encodeQr("x".repeat(287)).size)
    }
