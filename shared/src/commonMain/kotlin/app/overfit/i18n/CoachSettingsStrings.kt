    val copyPrompts: String,
    val promptsHint: String,
    val story: String,
    // Model picker
    val accessTitle: String,
    val segCredit: String,
    val segOwnKey: String,
    val creditModels: String,
    val perMessage: (price: String) -> String,
    val creditNote: String,
    val creditTapToLoad: String,
    val provider: String,
    val apiKey: String,
    val keyPlaceholder: String,
    val savedKey: (last4: String) -> String,
    val test: String,
    val testing: String,
    val keyOk: (count: Int) -> String,
    val keyInvalid: String,
    val keyNoCredit: String,
    val keyRateLimited: String,
    val keyNetwork: String,
    val keyFailed: (status: Int) -> String,
    val keyEmpty: String,
    val model: String,
    val modelPlaceholder: String,
    val suggestions: String,
    val runsDirect: (provider: String) -> String,
    val apply: String,
    val needKey: String,
    // Coach profile
    val profileIntro: String,
    val goal: String,
    val goalMuscle: String,
    val goalStrength: String,
    val goalFatLoss: String,
    val goalFitness: String,
    val experience: String,
    val expBeginner: String,
    val expIntermediate: String,
    val expAdvanced: String,
    val daysPerWeek: String,
    val height: String,
    val weight: String,
    val weightNone: String,
    val weightHint: String,
    val equipment: String,
    val equipmentPlaceholder: String,
    val limitations: String,
    val limitationsPlaceholder: String,
    val save: String,
    val saved: String,
    // Coach instructions
    val baseTitle: String,
    val baseHint: String,
    val showAll: String,
    val showLess: String,
    val additionTitle: String,
    val additionPlaceholder: String,
    val additionHint: String,
    val resetDefault: String,
    // Prompts
    val promptsIntro: String,
    // Credit popup
    val creditTitle: String,
    val neverExpires: String,
    val topUp: String,
    val topUpElsewhere: String,
    /** The one button that opens the web purchase page (the amount is chosen there). */
    val topUpOpen: String,
    /** Under that button: the amounts the purchase page offers ("5 €", "50 €"). */
    val topUpChooseAmount: (min: String, max: String) -> String,
    /** Coach profile: allowed height range, shown at the field while the value is outside it. */
    val heightRange: String,
    val openCreditPage: String,
    val billing: String,
    val billingEmpty: String,
    val allRequests: String,
    val close: String,
    val creditChip: (balance: String) -> String,
)

