    val optInButton: String,
    val demoBanner: String,
    val demoExit: String,
    val loading: String,
    val unreachable: String,
    val retry: String,
    val balanceLabel: String,
    /** Credit as an amount: always "X € Guthaben", never a bare euro amount (real money is a price). */
    val creditAmount: (amount: String) -> String,
    val topUp: String,
    /** Heading above the store packages. */
    val storeChannel: String,
    /** One store package: credit and the (higher) store price, both shown. */
    val storePackage: (credit: String, price: String) -> String,
    val storeSoon: String,
    val topUpNote: String,
    /** Honest one-liner under the packages; the argument is the markup in percent. */
    val pricesNote: (markupPercent: String) -> String,
    val pricesHow: String,
    val ledger: String,
    val ledgerEmpty: String,
    val ledgerUsage: String,
    val ledgerPurchase: String,
    /** Other credit (admin credit, credit of older accounts). */
    val ledgerCredit: String,
    /** Other debit (corrections of older accounts). */
    val ledgerDebit: String,
    val ledgerKindPaid: String,
    val ledgerKindCredited: String,
    val ledgerKindUsed: String,
    val ledgerKindRefunded: String,
    val ledgerKindDeducted: String,
    val ledgerTokens: (input: Long, output: Long) -> String,
    /** Booking answered by a replacement model; the argument is the model the user chose (its price was charged). */
    val ledgerFallback: (chosen: String) -> String,
    val loadMore: String,
    val recovery: String,
    val recoveryText: String,
    val recoveryCreate: String,
    val recoveryReplaceWarning: String,
    val recoveryCopy: String,
    val recoveryCopied: String,
    val restoreTitle: String,
    val restorePlaceholder: String,
    val restoreAction: String,
    val restoreDone: String,
    val restoreInvalid: String,
    val aiFuelDescription: String,
    val aiFuelOpen: String,
    val devTitle: String,
    val devBackendUrl: String,
    val devBackendHint: String,
    val devActive: (url: String) -> String,
    val devNotConfigured: String,
    val devSave: String,
    val devUnlocked: String,
    val vibration: String,
)

