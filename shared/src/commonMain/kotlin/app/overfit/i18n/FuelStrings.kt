    val creditAmount: (amount: String) -> String,
    /** Count of gifted coach reviews, e.g. "5 geschenkte Auswertungen". */
    val giftReviews: (count: Int) -> String,
    /** Split of the credit into bought and gifted. */
    val balanceSplit: (bought: String, gifted: String) -> String,
    val giftedFirst: String,
    /** Cost line of a coach answer paid with a gifted review. */
    val answerGifted: String,
    val giftReviewsExpiring: (count: Int, date: String) -> String,
    /** Which requests the gifted reviews cover; the argument is the real model name. */
    val giftReviewsScope: (model: String) -> String,
    val topUp: String,
    /** Heading above the store packages. */
    val storeChannel: String,
    /** One store package: credit and the (higher) store price, both shown. */
    val storePackage: (credit: String, price: String) -> String,
    val storeSoon: String,
    val topUpNote: String,
    /** Honest one-liner under the packages; the argument is the markup in percent. */
    val pricesNote: (markupPercent: String) -> String,
    val pricesHow: String,
    val ledger: String,
    val ledgerEmpty: String,
    val ledgerUsage: String,
    val ledgerPurchase: String,
    val ledgerInviteBonus: String,
    val ledgerInviteReward: String,
    val ledgerTestCredit: String,
    val ledgerInviteExpired: String,
    val ledgerGiftReviewUsage: String,
    /** Change of gifted reviews in a booking, e.g. "+5 Auswertungen" / "−1 Auswertung". */
    val ledgerReviews: (delta: Int) -> String,
    val ledgerKindPaid: String,
    val ledgerKindGifted: String,
    val ledgerKindUsed: String,
    val ledgerKindRefunded: String,
    val ledgerKindExpired: String,
    val ledgerTokens: (input: Long, output: Long) -> String,
    /** Booking answered by a replacement model; the argument is the model the user chose (its price was charged). */
    val ledgerFallback: (chosen: String) -> String,
    val loadMore: String,
    val recovery: String,
    val recoveryText: String,
    val recoveryCreate: String,
    val recoveryReplaceWarning: String,
    val recoveryCopy: String,
    val recoveryCopied: String,
    val restoreTitle: String,
    val restorePlaceholder: String,
    val restoreAction: String,
    val restoreDone: String,
    val restoreInvalid: String,
    val invite: String,
    val inviteShow: String,
    val inviteShowText: (reviews: Int) -> String,
    /** What the gifted reviews cover and when they expire. */
    val inviteGiftNote: (model: String, days: Int) -> String,
    val inviteName: String,
    val inviteNameHint: String,
    val inviteNamePlaceholder: String,
    val inviteRotates: (seconds: Int) -> String,
    val inviteCount: (used: Int, limit: Int) -> String,
    val inviteRedeem: String,
    val inviteRedeemText: String,
    val inviteScan: String,
    val invitePaste: String,
    val invitePastePlaceholder: String,
    val inviteRedeemAction: String,
    val inviteNoCode: String,
    val inviteCameraDenied: String,
    val inviteErrInvalid: String,
    val inviteErrUsed: String,
    val inviteErrExpired: String,
    val inviteErrSelf: String,
    val inviteErrAlready: String,
    val inviteErrDevice: String,
    val inviteErrInviterLimit: String,
    val inviteErrBudget: String,
    val inviteErrAttestation: String,
    val inviteErrRateLimited: String,
    val inviteErrNetwork: String,
    val inviteErrGeneric: String,
    val revealFrom: (name: String?) -> String,
    /** Caption under the counted-up number on the reveal. */
    val revealReviews: (count: Int) -> String,
    val revealClose: String,
    val aiFuelDescription: String,
    val aiFuelOpen: String,
    val devTitle: String,
    val devBackendUrl: String,
    val devBackendHint: String,
    val devActive: (url: String) -> String,
    val devNotConfigured: String,
    val devSave: String,
    val devUnlocked: String,
    val vibration: String,
)

