/**
 * Texts of the coach credit. Same rule as [Strings]: German and English are both
 * required (a missing translation does not compile). Kept in its own file so parallel work on [Strings] does not collide.
 */
class FuelStrings(
    val language: Language,
    val fuel: String,
    val fuelTagline: String,
    val fuelRowSoon: String,
    val fuelRowDemo: String,
    val fuelSoonTitle: String,
    val fuelSoonText: String,
    val demoView: String,
    val optInText: String,
