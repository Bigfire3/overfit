/**
 * Texts of the coach credit and the invite (referral) program. Same rule as [Strings]: German and English are both
 * required (a missing translation does not compile). Kept in its own file so parallel work on [Strings] does not collide.
 */
class FuelStrings(
    val language: Language,
    val fuel: String,
